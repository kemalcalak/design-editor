/// Whether `label` asks the reader to do something.
pub(crate) fn calls_to_action(label: &str) -> bool {
    let lower = label.to_lowercase();
    if UNSPACED_VERBS.iter().any(|verb| lower.contains(verb)) {
        return true;
    }
    let words = spaced_words(label);
    let Some(first) = words.first() else {
        return false;
    };
    let pre_order = words.len() > 1 && first == "pre" && words[1] == "order";
    if pre_order || EN_VERBS.contains(&first.as_str()) {
        return true;
    }
    let spaced = format!(" {} ", words.join(" "));
    EN_OFFERS
        .iter()
        .chain(VERBS)
        .filter(|verb| !unspaced(verb))
        .any(|verb| says(&lower, &spaced, verb))
        || words.iter().any(|word| turkish_verb(word))
}

/// A Turkish verb: a short one as a whole word, a stem with its suffix.
fn turkish_verb(word: &str) -> bool {
    // `İ` lowercases to `i` plus a combining dot (`İndirin`).
    let word = word.replace('\u{307}', "");
    let word = word.as_str();
    if TR_NOUNS.iter().any(|noun| word.starts_with(noun)) {
        return false;
    }
    TR_WORDS.contains(&word)
        || TR_STEMS.iter().any(|stem| {
            word.strip_prefix(stem)
                .is_some_and(|rest| rest.chars().count() <= TR_SUFFIX_MAX)
        })
}

#[cfg(test)]
mod tests {
    use super::calls_to_action;

    #[test]
    fn calls_to_action_in_every_language() {
        for label in [
            "Get tickets",
            "READ MORE",
            "PRE-ORDER NOW",
            "FREE TRIAL",
            "Schedule a call",
            "JETZT KAUFEN",
            "Mehr erfahren",
            "Ändere dein Bild",
            "COMPRAR AHORA",
            "Sube tu foto",
            "Achetez maintenant",
            "Купить сейчас",
            "अभी खरीदें",
            "Mua ngay",
            "Beli sekarang",
            "Hemen satın alın",
            "İndirin",
            "点击这里查看图片",
            "今すぐ購入",
            "지금 구매하기",
            "ซื้อเลย",
        ] {
            assert!(calls_to_action(label), "{label}");
        }
    }

    #[test]
    fn labels_that_name_something_are_no_calls() {
        for label in [
            "PRIMARY LOCKUP",
            "Reading list",
            "99 TL indirim",
            "Main",
            "SOUNDX",
            "Weight",
            "1.62 kg",
            "Drop logo",
            "Okul",
            "Sold out",
            "新品",
        ] {
            assert!(!calls_to_action(label), "{label}");
        }
    }
}
